const clients: QueryClient[] = []

/** Supplies native delivery controls while the real Settings adapter and category forms run.
 * Called by these UI tests; the existing MSW fixture owns category responses.
 * @example const fixture = categoryBridge()
 */
function categoryBridge() {
  const listeners = new Set<() => void>()
  const read = vi.fn<OfflineSettingsAPI['read']>(async (owner) => ({
    generation: owner === 'account-a' ? 2 : 3,
    preferences: null,
  }))
  const consume = vi.fn<OfflineSettingsAPI['consumeCategoryRequest']>(
    async () => null,
  )
  const categoryCreated = vi.fn<OfflineSettingsAPI['categoryCreated']>(
    async () => true,
  )
  const bridge: OfflineSettingsAPI = {
    version: 1,
    read,
    prepare: async () => true,
    patch: async () => ({ ok: false, reason: 'account-changed' }),
    onChanged: () => () => undefined,
    onManageCategories: (listener) => {
      listeners.add(listener)
      return () => listeners.delete(listener)
    },
    consumeCategoryRequest: consume,
    categoryCreated,
    refreshCategories: async () => undefined,
  }
  Object.defineProperty(window, 'electronAPI', {
    configurable: true,
    writable: true,
    value: { offlineSettings: bridge },
  })
  const client = new QueryClient({
    defaultOptions: { mutations: { retry: false }, queries: { retry: false } },
  })
  clients.push(client)
  const element = (
    <QueryClientProvider client={client}>
      <OfflineCategoryManagement />
      <Toaster />
    </QueryClientProvider>
  )
  return {
    read,
    consume,
    categoryCreated,
    element,
    notify: (): void => {
      for (const listener of listeners) listener()
    },
  }
}

/** Drains promise adoption and React updates before asserting an obsolete request stayed invisible.
 * @example await settleNativeDelivery()
 */
async function settleNativeDelivery(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0))
  })
}

beforeAll(() => orpcServer.listen({ onUnhandledFrame: 'error' }))
beforeEach(() => {
  auth.owner = 'account-a'
  resetOrpcServer([general])
})
afterEach(() => {
  cleanup()
  for (const client of clients.splice(0)) client.clear()
  toast.dismiss()
  delete window.electronAPI
  vi.restoreAllMocks()
  orpcServer.resetHandlers()
})
afterAll(() => orpcServer.close())

// Generated by /ship Step 7 coverage audit, pass 2.
// Value: protects=category requests from a departed account or stale generation never open a form;
// fails_when=old delivery survives cleanup or mismatched generation is treated as current;
// why_new=main IPC tests do not mount the remote Settings request consumer;
// seam=none; no_claim=live Clerk or native IPC (synthetic bridge; real forms and MSW category API).
test('category requests stay closed after an account switch or stale generation and open only for the current request', async () => {
  // Arrange
  const fixture = categoryBridge()
  let release!: (request: OfflineCategoryRequest) => void
  fixture.consume.mockImplementationOnce(
    async () =>
      new Promise((resolve) => {
        release = resolve
      }),
  )
  const view = render(fixture.element)
  await waitFor(() => expect(fixture.consume).toHaveBeenCalledOnce())

  // Act
  auth.owner = 'account-b'
  view.rerender(
    <QueryClientProvider client={clients[0]!}>
      <OfflineCategoryManagement />
      <Toaster />
    </QueryClientProvider>,
  )
  await waitFor(() => expect(fixture.read).toHaveBeenCalledWith('account-b'))
  await act(async () =>
    release({
      action: 'create',
      generation: 2,
      initialName: 'Private A request',
    }),
  )
  await settleNativeDelivery()

  // Assert
  expect(screen.queryByRole('dialog')).toBeNull()
  auth.owner = 'account-a'
  view.rerender(
    <QueryClientProvider client={clients[0]!}>
      <OfflineCategoryManagement />
      <Toaster />
    </QueryClientProvider>,
  )
  await settleNativeDelivery()
  expect(screen.queryByRole('dialog')).toBeNull()

  fixture.consume.mockResolvedValueOnce({
    action: 'create',
    generation: 1,
    initialName: 'Stale request',
  })
  act(fixture.notify)
  await settleNativeDelivery()
  expect(screen.queryByRole('dialog')).toBeNull()

  fixture.consume.mockResolvedValueOnce({
    action: 'create',
    generation: 2,
    initialName: 'Current request',
  })
  act(fixture.notify)
  expect(
    await screen.findByRole('textbox', { name: 'New category name' }),
  ).toHaveValue('Current request')
  expect(screen.getByRole('dialog', { name: 'New category' })).toBeVisible()
  expect(fixture.categoryCreated).not.toHaveBeenCalled()
})

// Generated by /ship Step 7 coverage audit, pass 2.
// Value: protects=confirmed category creation keeps its account identity and explains failed native selection;
// fails_when=the bridge receives a different owner/generation/ID or rejected selection is silently accepted;
// why_new=picker tests bypass the remote Settings adapter and its native selection acknowledgement;
// seam=none; no_claim=live provider acceptance (synthetic bridge and MSW; real form, query and toast).
test('created categories are forwarded to the current native account and rejected selection shows reconnect guidance', async () => {
  // Arrange
  const user = userEvent.setup()
  const fixture = categoryBridge()
  const errorToast = vi.spyOn(toast, 'error')
  fixture.consume.mockResolvedValueOnce({
    action: 'create',
    generation: 2,
    initialName: 'Reading',
  })
  fixture.categoryCreated.mockResolvedValueOnce(false)
  render(fixture.element)
  expect(
    await screen.findByRole('textbox', { name: 'New category name' }),
  ).toHaveValue('Reading')

  // Act
  await user.click(screen.getByRole('button', { name: 'Add' }))

  // Assert
  await waitFor(() =>
    expect(fixture.categoryCreated).toHaveBeenCalledWith('account-a', 2, 2),
  )
  expect(
    await screen.findByText(
      'Category created. Select it after reconnecting LiveEditor.',
    ),
  ).toBeVisible()
  expect(readCategories().find((category) => category.id === 2)?.name).toBe(
    'Reading',
  )
  expect(screen.queryByRole('dialog')).toBeNull()

  fixture.consume.mockResolvedValueOnce({
    action: 'create',
    generation: 2,
    initialName: 'Writing',
  })
  act(fixture.notify)
  expect(
    await screen.findByRole('textbox', { name: 'New category name' }),
  ).toHaveValue('Writing')
  await user.click(screen.getByRole('button', { name: 'Add' }))
  await waitFor(() =>
    expect(fixture.categoryCreated).toHaveBeenCalledWith('account-a', 2, 3),
  )
  await settleNativeDelivery()
  expect(readCategories().find((category) => category.id === 3)?.name).toBe(
    'Writing',
  )
  expect(screen.queryByRole('dialog')).toBeNull()
  expect(errorToast).toHaveBeenCalledOnce()
})
