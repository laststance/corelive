import { act, cleanup, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, expect, test, vi } from 'vitest'

import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuTrigger,
} from '@/components/ui/dropdown-menu'

import { LogoutButton } from './LogoutButton'

const clerk = vi.hoisted(() => ({ signOut: vi.fn(async () => undefined) }))
vi.mock('@clerk/nextjs', () => ({ useClerk: () => clerk }))
vi.mock('@/lib/logger', () => ({ log: { error: vi.fn() } }))

/** Mounts the actual menu item so tests click the same logout handler as the account menu.
 * The provider is synthetic; the native acknowledgement is supplied by each test.
 * @example mountLogoutMenu()
 */
function mountLogoutMenu() {
  return render(
    <DropdownMenu>
      <DropdownMenuTrigger>Account menu</DropdownMenuTrigger>
      <DropdownMenuContent>
        <LogoutButton />
      </DropdownMenuContent>
    </DropdownMenu>,
  )
}

/** Installs only the remote auth capability used by this component, without native launches.
 * @example installAuth({ logout, sessionUnavailable: async () => undefined })
 */
function installAuth(auth: {
  logout: () => Promise<boolean>
  sessionUnavailable?: () => Promise<void>
}): void {
  Object.defineProperty(window, 'electronAPI', {
    configurable: true,
    writable: true,
    value: { auth },
  })
}

/** Drains the click handler's asynchronous continuation before testing a negative sign-out result.
 * @example await settleLogout()
 */
async function settleLogout(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0))
  })
}

afterEach(() => {
  cleanup()
  delete window.electronAPI
  clerk.signOut.mockClear()
})

// Generated by /ship Step 7 coverage audit, pass 2.
// Value: protects=failed or unavailable native saving prevents explicit Clerk sign-out;
// fails_when=the logout button signs out before native acknowledgement or ignores false/rejected results;
// why_new=controller save tests do not invoke the remote account menu handler;
// seam=none; no_claim=real Clerk sign-out or native IPC (synthetic capabilities; real menu interaction).
test('logout keeps the account signed in while native saving is pending, refused or fails', async () => {
  // Arrange
  const user = userEvent.setup()
  let finish!: (saved: boolean) => void
  const logout = vi.fn(
    async (): Promise<boolean> =>
      new Promise((resolve) => {
        finish = resolve
      }),
  )
  installAuth({ logout, sessionUnavailable: async () => undefined })
  mountLogoutMenu()

  // Act
  await user.click(screen.getByRole('button', { name: 'Account menu' }))
  await user.click(screen.getByRole('menuitem', { name: 'Log out' }))

  // Assert
  expect(logout).toHaveBeenCalledOnce()
  expect(clerk.signOut).not.toHaveBeenCalled()
  finish(false)
  await settleLogout()
  expect(clerk.signOut).not.toHaveBeenCalled()

  logout.mockRejectedValueOnce(new Error('Native save unavailable'))
  await user.click(screen.getByRole('button', { name: 'Account menu' }))
  await user.click(screen.getByRole('menuitem', { name: 'Log out' }))
  await settleLogout()
  expect(logout).toHaveBeenCalledTimes(2)
  expect(clerk.signOut).not.toHaveBeenCalled()
})

// Generated by /ship Step 7 coverage audit, pass 2.
// Value: protects=acknowledged native logout and existing browser/older-preload logout remain available;
// fails_when=sign-out starts before a successful acknowledgement or new capability checks block old clients;
// why_new=the refusal path alone cannot detect an implementation that prevents every logout;
// seam=none; no_claim=provider or OS acceptance (synthetic auth; actual React menu handler).
test('logout continues after the native lock succeeds and remains compatible with older preloads and browsers', async () => {
  // Arrange
  const user = userEvent.setup()
  let finish!: (saved: boolean) => void
  const logout = vi.fn(
    async (): Promise<boolean> =>
      new Promise((resolve) => {
        finish = resolve
      }),
  )
  installAuth({ logout, sessionUnavailable: async () => undefined })
  mountLogoutMenu()

  // Act
  await user.click(screen.getByRole('button', { name: 'Account menu' }))
  await user.click(screen.getByRole('menuitem', { name: 'Log out' }))
  expect(clerk.signOut).not.toHaveBeenCalled()
  finish(true)

  // Assert
  await waitFor(() => expect(clerk.signOut).toHaveBeenCalledOnce())
  cleanup()
  const legacyLogout = vi.fn(async () => false)
  installAuth({ logout: legacyLogout })
  mountLogoutMenu()
  await user.click(screen.getByRole('button', { name: 'Account menu' }))
  await user.click(screen.getByRole('menuitem', { name: 'Log out' }))
  await waitFor(() => expect(clerk.signOut).toHaveBeenCalledTimes(2))
  expect(legacyLogout).not.toHaveBeenCalled()

  cleanup()
  delete window.electronAPI
  mountLogoutMenu()
  await user.click(screen.getByRole('button', { name: 'Account menu' }))
  await user.click(screen.getByRole('menuitem', { name: 'Log out' }))
  await waitFor(() => expect(clerk.signOut).toHaveBeenCalledTimes(3))
})
